#!/usr/bin/env python3
"""Emit literal Solidity ranges, independently of the contract's bit packing.

Run from any directory. Python 3.9+ and IANA America/New_York tzdata required.
Normal Forge tests need neither Python nor filesystem/FFI permissions.
The hand-written calendar below intentionally matches the *policy* of the
2027 deployment calendar, but does not read or call the Solidity encoder.
"""
from __future__ import annotations

import argparse
from datetime import date, datetime, time, timedelta, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

UTC = timezone.utc
NY = ZoneInfo("America/New_York")
FIXED_EST = timezone(timedelta(hours=-5))
OUTPUT = Path(__file__).resolve().parents[1] / "test" / "MarketHoursCorpus.t.sol"

# Weekday -> local opening and closing minutes. End=1440 means next midnight.
# Monday=0. Sunday evening to Friday evening; NOT regular NYSE daytime hours.
WEEK = {0: (0, 1440), 1: (0, 1440), 2: (0, 1440), 3: (0, 1440),
        4: (0, 1200), 5: (0, 0), 6: (1200, 1440)}
CLOSED_2027 = {
    date(2027, 1, 1), date(2027, 1, 18), date(2027, 2, 15),
    date(2027, 3, 26), date(2027, 5, 31), date(2027, 6, 18),
    date(2027, 7, 5), date(2027, 9, 6), date(2027, 11, 25),
    date(2027, 12, 24),
}
EARLY_CLOSE_2027 = {date(2027, 11, 26): 13 * 60}


def market_ranges(tz):
    ranges = []
    day = date(2027, 1, 1)
    while day < date(2028, 1, 1):
        opening, closing = WEEK[day.weekday()]
        if day in CLOSED_2027:
            opening = closing = 0
        if day in EARLY_CLOSE_2027:
            closing = min(closing, EARLY_CLOSE_2027[day])
        # Split at local boundaries using zoneinfo for UTC offsets. No custom
        # DST arithmetic, weekday algorithm, or packed-word decoder is copied.
        boundaries = sorted({0, 1440, opening, closing})
        midnight = datetime.combine(day, time(), tzinfo=tz)
        for lo, hi in zip(boundaries, boundaries[1:]):
            start = int((midnight + timedelta(minutes=lo)).timestamp())
            end = int((midnight + timedelta(minutes=hi)).timestamp())
            ranges.append((start, end, opening <= lo < closing, str(day)))
        day += timedelta(days=1)
    return ranges


def dst_ranges():
    # Independent seasonal UTC intervals, including exact transition seconds.
    # Includes multiple leap years and varying March/November transition dates.
    begin = int(datetime(2020, 1, 1, tzinfo=UTC).timestamp())
    finish = int(datetime(2041, 1, 1, tzinfo=UTC).timestamp())

    def is_dst(ts):
        return bool(datetime.fromtimestamp(ts, NY).dst())

    ranges = []
    start = previous = begin
    value = is_dst(begin)
    probe = begin + 6 * 3600
    while probe <= finish:
        next_value = is_dst(probe)
        if next_value != value:
            lo, hi = previous, probe
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if is_dst(mid) == value:
                    lo = mid
                else:
                    hi = mid
            ranges.append((start, hi, value, "DST" if value else "standard"))
            start, value = hi, next_value
        previous = probe
        probe += 6 * 3600
    ranges.append((start, finish, value, "DST" if value else "standard"))
    return ranges


def validate(ranges):
    assert ranges and {row[2] for row in ranges} == {True, False}
    for i, (start, end, _, _) in enumerate(ranges):
        assert end > start
        if i:
            assert ranges[i - 1][1] == start, "gap or overlap"


def utc(ts):
    return datetime.fromtimestamp(ts, UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def emit_function(name, ranges):
    lines = [f"    // {len(ranges)} contiguous [start,end) records.",
             f"    function {name}() internal pure override returns (bytes memory) {{",
             "        return"]
    for start, end, value, label in ranges:
        encoded = start.to_bytes(8, "big") + end.to_bytes(8, "big") + bytes([value])
        lines.append(f"            // {label}: [{utc(start)}, {utc(end)}) expected={str(value).lower()}")
        lines.append(f'            hex"{encoded.hex()}"')
    lines[-1] += ";"
    lines.append("    }")
    return "\n".join(lines)


def render():
    corpora = {"marketCorpus": market_ranges(NY),
               "fixedCorpus": market_ranges(FIXED_EST), "dstCorpus": dst_ranges()}
    for ranges in corpora.values():
        validate(ranges)
    text = '''// SPDX-License-Identifier: MIT
pragma solidity 0.8.24;

// GENERATED by utils/generate_market_calendar.py. Edit the generator, not this file.
// Calendar: 2027 Sunday 20:00 through Friday 20:00 New York, minus listed holidays.
// DST reference: Python zoneinfo America/New_York, 2020 through 2040 inclusive.
// Fixed-offset calendar: the same 2027 policy with UTC-05:00 all year.
// No runtime files, Python, FFI, live RPC, or clock dependencies.
import "./Utils/MarketHoursCorpusTests.sol";

abstract contract GeneratedMarketCalendarCorpus is CalendarCorpus {
'''
    text += "\n\n".join(emit_function(name, rows) for name, rows in corpora.items())
    text += '''
}

contract MarketHoursCorpusTest is MarketHoursCorpusTests, GeneratedMarketCalendarCorpus {}

contract MarketHoursOperationsCorpusTest is MarketHoursOperationsCorpusTests, GeneratedMarketCalendarCorpus {}
'''
    return text, corpora


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated source without writing")
    args = parser.parse_args()
    text, corpora = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit(f"Generated source differs: regenerate {OUTPUT}")
        print(f"Verified {OUTPUT}")
    else:
        OUTPUT.write_text(text)
        print(f"Wrote {OUTPUT}")
    for name, rows in corpora.items():
        print(f"{name}: {len(rows)} ranges, {utc(rows[0][0])} to {utc(rows[-1][1])}")


if __name__ == "__main__":
    main()
